export function isValidLocation(location) {
  if (!location || typeof location !== 'object') return false;
  const lat = typeof location.latitude === 'number' ? location.latitude : location.lat;
  const lon = typeof location.longitude === 'number' ? location.longitude : location.lon;
  return (
    typeof lat === 'number' &&
    !isNaN(lat) &&
    typeof lon === 'number' &&
    !isNaN(lon) &&
    lat >= -90 &&
    lat <= 90 &&
    lon >= -180 &&
    lon <= 180 &&
    typeof location.name === 'string' &&
    location.name.trim().length > 0
  );
}

export function getLocationById(id) {
  if (!id) return LAGOS_LOCATIONS[10]; // Default to Ikeja
  const cleanId = String(id).toLowerCase().trim();
  const match = LAGOS_LOCATIONS.find(loc => loc.id === cleanId || loc.name.toLowerCase() === cleanId);
  return match || LAGOS_LOCATIONS[10]; // Default to Ikeja
}

export function searchLocations(query) {
  if (!query || typeof query !== 'string' || !query.trim()) {
    return [...LAGOS_LOCATIONS];
  }
  const q = query.toLowerCase().trim();
  return LAGOS_LOCATIONS.filter(loc => {
    const matchName = loc.name.toLowerCase().includes(q);
    const matchId = loc.id.toLowerCase().includes(q);
    const matchAreas = loc.popularAreas && loc.popularAreas.some(area => area.toLowerCase().includes(q));
    return matchName || matchId || matchAreas;
  });
}

/**
 * Lagos State Approximate Geographic Boundaries:
 * Lat: 6.15°N to 6.90°N
 * Lon: 2.60°E to 4.30°E
 * Max acceptable distance to nearest LGA representative center: ~35 km
 */
export const LAGOS_GEO_BOUNDS = {
  minLat: 6.15,
  maxLat: 6.90,
  minLon: 2.60,
  maxLon: 4.30,
  maxDistanceToCenterKm: 35.0
};

/**
 * Determines whether a given latitude and longitude coordinate falls within
 * the supported Lagos State geographic area.
 * @param {number} latitude 
 * @param {number} longitude 
 * @returns {boolean}
 */
export function isWithinLagosArea(latitude, longitude) {
  const lat = Number(latitude);
  const lon = Number(longitude);

  if (isNaN(lat) || isNaN(lon)) return false;

  // 1. Bounding box check
  const inBoundingBox =
    lat >= LAGOS_GEO_BOUNDS.minLat &&
    lat <= LAGOS_GEO_BOUNDS.maxLat &&
    lon >= LAGOS_GEO_BOUNDS.minLon &&
    lon <= LAGOS_GEO_BOUNDS.maxLon;

  if (!inBoundingBox) return false;

  // 2. Minimum distance to any LGA center check
  let minDistance = Infinity;
  for (const loc of LAGOS_LOCATIONS) {
    const d = calculateHaversineKm(lat, lon, loc.lat, loc.lon);
    if (d < minDistance) {
      minDistance = d;
    }
  }

  return minDistance <= LAGOS_GEO_BOUNDS.maxDistanceToCenterKm;
}

/**
 * Reusable Haversine distance calculator for location matching
 */
function calculateHaversineKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const toRad = (deg) => (deg * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/**
 * Identifies the nearest supported Lagos LGA for a given GPS coordinate.
 *
 * IMPORTANT METHODOLOGY NOTE:
 * This matching implementation uses an approximate nearest-representative-coordinate
 * approach based on the reference coordinates stored for each of the 20 official Lagos LGAs.
 * It is not an official administrative boundary polygon test, but provides robust, reliable
 * nearest-LGA resolution. The architecture is modular so that official administrative
 * boundary polygons can be substituted in the future without breaking callers.
 *
 * @param {number} latitude User GPS latitude
 * @param {number} longitude User GPS longitude
 * @returns {{
 *   lga: Object|null,
 *   isWithinLagos: boolean,
 *   distanceKm: number,
 *   method: string,
 *   message?: string
 * }}
 */
export function findNearestLGA(latitude, longitude) {
  const lat = Number(latitude);
  const lon = Number(longitude);

  if (isNaN(lat) || isNaN(lon) || lat < -90 || lat > 90 || lon < -180 || lon > 180) {
    return {
      lga: null,
      isWithinLagos: false,
      distanceKm: Infinity,
      method: "approximate_nearest_coordinate",
      message: "Invalid GPS coordinates provided."
    };
  }

  // Find nearest LGA by Haversine distance
  let closestLga = null;
  let minDistance = Infinity;

  for (const loc of LAGOS_LOCATIONS) {
    const dist = calculateHaversineKm(lat, lon, loc.lat, loc.lon);
    if (dist < minDistance) {
      minDistance = dist;
      closestLga = loc;
    }
  }

  // Check if coordinates belong to supported Lagos geographic area
  const withinLagos =
    lat >= LAGOS_GEO_BOUNDS.minLat &&
    lat <= LAGOS_GEO_BOUNDS.maxLat &&
    lon >= LAGOS_GEO_BOUNDS.minLon &&
    lon <= LAGOS_GEO_BOUNDS.maxLon &&
    minDistance <= LAGOS_GEO_BOUNDS.maxDistanceToCenterKm;

  if (!withinLagos) {
    return {
      lga: null,
      nearestCandidate: closestLga,
      isWithinLagos: false,
      distanceKm: Math.round(minDistance * 10) / 10,
      method: "approximate_nearest_coordinate",
      message: "We detected your location, but it is outside the currently supported Lagos State coverage."
    };
  }

  return {
    lga: closestLga,
    isWithinLagos: true,
    distanceKm: Math.round(minDistance * 10) / 10,
    method: "approximate_nearest_coordinate"
  };
}
